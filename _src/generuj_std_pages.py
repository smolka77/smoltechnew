def pic(src: str, alt: str, w: int, h: int, eager: bool = False) -> str:
    stem = src.rsplit(".", 1)[0]
    pri = ' fetchpriority="high"' if eager else ' loading="lazy"'
    return (
        f'<picture>\n'
        f'          <source srcset="{escape(stem)}.webp" type="image/webp">\n'
        f'          <img src="{escape(src)}" alt="{escape(alt)}" width="{w}" height="{h}"'
        f'{pri} decoding="async">\n'
        f'        </picture>'
    )


def pad(vals: list[str], n: int) -> list[str]:
    vals = list(vals)
    if len(vals) == 1 and n > 1:
        return vals * n
    while len(vals) < n:
        vals.append("—")
    return vals[:n]


def matrix(models: list[str], rows: list[tuple[str, list[str]]], aria: str, wide: bool = False) -> str:
    n = len(models)
    cls = f"param-matrix param-matrix--{n} is-hl-1"
    if wide or n >= 7:
        cls += " param-matrix--wide"
    cells = [
        '<div class="param-matrix__cell param-matrix__head param-matrix__label" role="columnheader">Параметр</div>'
    ]
    for i, m in enumerate(models, 1):
        cells.append(
            f'<div class="param-matrix__cell param-matrix__head" role="columnheader" data-col="{i}">{escape(m)}</div>'
        )
    for label, vals in rows:
        vals = pad(vals, n)
        cells.append(
            f'<div class="param-matrix__cell param-matrix__label" role="rowheader">{escape(label)}</div>'
        )
        for i, v in enumerate(vals, 1):
            inner = f"<strong>{escape(v)}</strong>" if i == 1 and v not in {"—", "•/—", "•/•"} else escape(v)
            cells.append(
                f'<div class="param-matrix__cell param-matrix__val" data-col="{i}">{inner}</div>'
            )
    btns = []
    for i, m in enumerate(models, 1):
        active = " is-active" if i == 1 else ""
        pressed = "true" if i == 1 else "false"
        btns.append(
            f'<li><button class="model-strip__btn{active}" type="button" data-model="{i}" '
            f'aria-pressed="{pressed}"><span class="model-strip__name">{escape(m)}</span></button></li>'
        )
    return f'''    <div class="rv rv-d1" data-param-matrix>
      <ul class="model-strip" role="tablist" aria-label="{escape(aria)}">
        {"".join(btns)}
      </ul>
      <div class="{cls}">
        <div class="param-matrix__scroll">
          <div class="param-matrix__table" role="table" aria-label="{escape(aria)}">
            {chr(10).join(cells)}
          </div>
        </div>
      </div>
    </div>'''


def features(items: list[tuple[str, str]]) -> str:
    parts = []
    for t, p in items:
        parts.append(
            f'<article class="feature-rail__i"><h3>{escape(t)}</h3><p>{escape(p)}</p></article>'
        )
    return f'<div class="feature-rail">\n        {"".join(parts)}\n      </div>'


def ticks(items: list[str]) -> str:
    return "<ul class=\"ticks\">\n          " + "\n          ".join(
        f"<li>{escape(x)}</li>" for x in items
    ) + "\n        </ul>"


def choice(cards: list[dict]) -> str:
    bits = []
    for c in cards:
        bits.append(
            f'''      <a class="choice__card choice__card--link" href="{c["href"]}">
        <span class="tag">{escape(c["tag"])}</span>
        <h3>{escape(c["h"])}</h3>
        <p>{escape(c["p"])}</p>
        <span class="arrow-link">{escape(c["a"])}
          {ARR}
        </span>
      </a>'''
        )
    return '<div class="choice rv rv-d1">\n' + "\n".join(bits) + "\n    </div>"


def tile(href: str, no: str, img: str, alt: str, w: int, h: int, tag: str, h3: str, p: str, a: str) -> str:
    return f'''      <a class="tile" href="{href}">
        <div class="tile__media">
          <span class="tile__no">{no}</span>
          {pic(img, alt, w, h)}
        </div>
        <div class="tile__body">
          <span class="tag">{escape(tag)}</span>
          <h3>{escape(h3)}</h3>
          <p>{escape(p)}</p>
          <span class="arrow-link">{escape(a)}
            {ARR}
          </span>
        </div>
      </a>'''


